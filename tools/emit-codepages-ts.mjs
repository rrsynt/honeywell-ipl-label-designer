console.log('wrote services/ipl/codePages.ts');

// --- codePagesCjkData.ts: data only ----------------------------------------

const dataEntries = CJK.map(([n, label]) => {
    const g = golden(n);
    if (!g.flat || !g.singles || !g.leads) throw new Error(`codepages/${n}.json: not a DBCS golden`);
    const bytes = [];
    for (let i = 0; i < g.leads.length; i += 2) bytes.push(parseInt(g.leads.substr(i, 2), 16));
    const runs = [];
    for (const b of bytes) {
        const last = runs[runs.length - 1];
        if (last && b === last[1] + 1) last[1] = b;
        else runs.push([b, b]);
    }
    const leadRuns = '[' + runs.map(([a, b]) => `[0x${a.toString(16)}, 0x${b.toString(16)}]`).join(', ') + '] as const';
    const parts = [
        `whatwg: '${g.whatwg}'`,
        `leads: ${leadRuns}`,
        `flat: '${g.flat}'`,
        `singles: '${g.singles}'`,
    ];
    if (g.special) parts.push(`special: '${g.special}'`);
    return `    // ${label}\n    ${n}: {\n        ${parts.join(',\n        ')},\n    },`;
}).join('\n');

const dataSource = `// Raw double-byte code page tables for printer languages 30-33 (<SI>l).
//
// GENERATED by tools/emit-codepages-ts.mjs from testdata/codepages/*.json, which
// tools/gen-cjk-codepages.mjs produces from the WHATWG Encoding Standard's index
// files. Do not hand-edit: re-running the emitter overwrites this file, and
// tests/codePageCjk.test.ts pins every slot to Chromium's own TextDecoder.
//
// This module is imported DYNAMICALLY by services/ipl/codePages.ts so its
// ~250 KB stays out of the main chunk. The decoder that reads these tables is
// hand-written in services/ipl/dbcs.ts.

/** One page's raw data, still base64. Decoded on first use by cjkTable(). */
export interface CjkRawTable {
    /** The WHATWG label this table reproduces. */
    whatwg: string;
    /** Accepted lead-byte ranges, in row order. */
    leads: readonly (readonly [number, number])[];
    /** One slot per (lead, trail), row-major: base64 of little-endian u16. */
    flat: string;
    /** Bytes 0x80-0xFF that stand alone: base64 u16, 0xFFFF = not one. */
    singles: string;
    /** \`slot, cp1, cp2\` triples for 0xFFFE slots; cp2 is 0 for astral singles. */
    special?: string;
}

export const CJK_RAW: Record<number, CjkRawTable> = {
${dataEntries}
};
`;

writeFileSync(join(root, 'services', 'ipl', 'codePagesCjkData.ts'), dataSource, 'utf8');
console.log('wrote services/ipl/codePagesCjkData.ts');
