// Builds the committed tables in services/ipl/ from the goldens in
// testdata/codepages/. Kept as a script so the committed tables are always a
// mechanical transcription of an audited source — never hand-typed.
//
// Emits two files:
//   services/ipl/codePages.ts      — the 11 single-byte pages (n=10..20), the
//                                    decoder for them, and the entry points.
//   services/ipl/codePagesCjkData.ts — the four double-byte page tables
//                                    (n=30..33), data only.
//
// The DBCS *decoder* is NOT generated: it lives in services/ipl/dbcs.ts,
// hand-written and reviewed like any other code. Only the numbers are generated,
// which is what keeps `node tools/emit-codepages-ts.mjs` safe to re-run.
//
// Sources: tools/gen-codepages.mjs (GNU iconv) and tools/gen-cjk-codepages.mjs
// (WHATWG Encoding Standard). tests/codePage.test.ts and codePageCjk.test.ts
// compare every byte against these goldens.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const golden = (n) => JSON.parse(readFileSync(join(root, 'testdata', 'codepages', `${n}.json`), 'utf8'));

const PAGES = [
    [10, 'CP850 — DOS Latin 1'],
    [11, 'CP1250 — Central Europe'],
    [12, 'CP1251 — Cyrillic'],
    [13, 'CP1252 — Latin 1, Western Europe'],
    [14, 'CP1253 — Greek'],
    [15, 'CP1254 — Turkish'],
    [16, 'CP1255 — Hebrew'],
    [17, 'CP1256 — Arabic'],
    [18, 'CP1257 — Baltic Rim'],
    [19, 'CP1258 — Vietnamese'],
    [20, 'CP874 — Thai'],
];

const CJK = [
    [30, 'CP932 — Shift JIS, Japanese'],
    [31, 'CP936 — GB 2312, Simplified Chinese'],
    [32, 'CP949 — KSC5601, Korean Hangeul'],
    [33, 'CP950 — Big 5, Traditional Chinese'],
];

const tableLines = PAGES.map(([n, label]) => {
    const g = golden(n);
    if (g.table.length !== 128) throw new Error(`codepages/${n}.json: expected 128 entries`);
    return `    ${n}: { label: '${label}', table: '${g.table.map((c) => c.toString(16).padStart(4, '0')).join('')}' },`;
}).join('\n');

const cjkInfoLines = CJK.map(([n, label]) => {
    const g = golden(n);
    return `    ${n}: { label: '${label}', dbcs: '${g.whatwg}' },`;
}).join('\n');

const singleByteSource = `// IPL Printer Language / code page support (PRM p.133 "<SI>ln", 2.70 p.139).
//
// A code page maps the 0x80-0xFF bytes of print data onto real characters. The
// pipeline carries byte-strings (one char per byte) so Direct Graphics payloads
// stay byte-exact, which makes this the step that turns bytes into text.
//
// The single-byte tables are bundled rather than delegated to TextDecoder on
// purpose: on Node 20 / ICU 76.1, 5 of these 9 labels decode WRONG
// (windows-1250 0xB1 -> U+00B1 instead of U+0105, windows-1252 0x84 -> U+0084
// instead of U+201E, plus windows-1254/1257/1258). A committed table is
// identical in Node and the browser; TextDecoder is not.
//
// The double-byte pages (n=30..33) carry the same verdict for a different
// reason — see the header of services/ipl/dbcs.ts — and their tables live in
// codePagesCjkData.ts, loaded lazily because they are ~250 KB that only a
// stream selecting one of those pages ever needs.
//
// GENERATED by tools/emit-codepages-ts.mjs from testdata/codepages/*.json,
// which tools/gen-codepages.mjs (GNU iconv) and tools/gen-cjk-codepages.mjs
// (WHATWG Encoding Standard) produce. Do not hand-edit the tables: the emitter
// rewrites this file. The decoder below IS hand-written and belongs here.

import { decodeCjkTable, decodeDbcs, type DbcsTable, type DbcsRawTable } from './dbcs';

/** Null until the table module lands; see ensureCjkReady below. */
let cjkRaw: Record<number, DbcsRawTable> | null = null;

/** A code page we can decode, plus the ones we deliberately leave alone. */
export interface CodePageInfo {
    /** Human label for the issues panel and the viewer settings readout. */
    label: string;
    /** 128 code points for bytes 0x80-0xFF, concatenated 4-digit hex. */
    table?: string;
    /**
     * True for n=0..9: the printer substitutes a small set of characters
     * (Appendix B), which is NOT a code page. Decoding must leave bytes alone.
     */
    resident?: boolean;
    /**
     * The WHATWG label of a double-byte page (n=30..33). Its table is loaded
     * lazily, so a decode that runs before the module arrives returns the
     * bytes untouched — see decodeCodePage.
     */
    dbcs?: string;
}

/** Printer language n -> code page (PRM p.133-134, 2.70 p.139-140). */
export const CODE_PAGES: Record<number, CodePageInfo> = {
    0: { label: 'U.S.A.', resident: true },
    1: { label: 'United Kingdom', resident: true },
    2: { label: 'Germany', resident: true },
    3: { label: 'Denmark', resident: true },
    4: { label: 'France', resident: true },
    5: { label: 'Sweden', resident: true },
    6: { label: 'Italy', resident: true },
    7: { label: 'Spain', resident: true },
    8: { label: '8-Bit ASCII', resident: true },
    9: { label: 'Switzerland', resident: true },
${tableLines}
${cjkInfoLines}
    40: { label: 'UTF-8' },
};

const REPLACEMENT = 0xfffd;

// ---------------------------------------------------------------------------
// Double-byte pages (n=30..33): the table module is imported on demand.
//
// Pulling it in eagerly would put ~190 KB of base64 in the main chunk for every
// user, when only a stream that says <SI>l30..33 ever reads it — the same
// trade-off barcodes.ts and xlsxImport.ts already make for bwip-js and SheetJS.
//
// UNTIL IT ARRIVES, decodeCodePage returns CJK bytes UNTOUCHED. That is not a
// silently wrong answer: it is exactly what the viewer showed before this
// feature existed, and the viewers re-parse once the module lands (the code
// equivalent of the bwipReady dependency in IPLViewerModal.tsx). A caller that
// cannot re-parse should await ensureCjkReady() first.
// ---------------------------------------------------------------------------

/** Tables decoded on first use, keyed by printer language. */
const cjkCache = new Map<number, DbcsTable>();
let cjkPromise: Promise<void> | null = null;

/**
 * The table for printer language \`n\`, decoded once. Undefined until
 * ensureCjkReady() has resolved.
 */
export const cjkTable = (n: number): DbcsTable | undefined => {
    const cached = cjkCache.get(n);
    if (cached) return cached;
    // Not loaded yet: a decode that arrives here must fall through to the raw
    // bytes, not throw into a parse. (Found in the browser: the unit tests all
    // await ensureCjkReady first, so none of them ever exercised this path.)
    if (!cjkRaw) return undefined;
    const raw = cjkRaw[n];
    if (!raw) return undefined;
    const table = decodeCjkTable(raw);
    cjkCache.set(n, table);
    return table;
};

/**
 * Load the double-byte tables. Resolves whether or not the import succeeds: a
 * failed load leaves CJK data as raw bytes, which beats throwing into a parse.
 */
export const ensureCjkReady = (): Promise<void> => {
    if (!cjkPromise) {
        cjkPromise = import('./codePagesCjkData')
            .then((m) => { cjkRaw = m.CJK_RAW; })
            .catch(() => { cjkRaw = null; });
    }
    return cjkPromise;
};

/** Synchronous probe for hot paths, mirroring isBarcodeEngineReady(). */
export const isCjkReady = (): boolean => cjkRaw !== null;

/**
 * Decode a byte-string under code page \`n\`.
 *
 * Unknown and resident (n=0..9) pages return the input untouched. For the
 * resident languages that is deliberate: they are the Appendix B character
 * SUBSTITUTION, not a code page, and apply through applyResidentCharset.
 */
export function decodeCodePage(s: string, n: number | undefined): string {
    if (n === undefined || n === null) return s;
    if (n === 40) return decodeUtf8(s);
    const info = CODE_PAGES[n];
    if (!info) return s;
    if (info.dbcs) {
        const page = cjkTable(n);
        return page ? decodeDbcs(s, page) : s;
    }
    if (info.resident || !info.table) return s;

    const table = info.table;
    let out = '';
    for (let i = 0; i < s.length; i++) {
        const code = s.charCodeAt(i);
        // The pipeline's byte-string uses one char per BYTE, so every value in
        // U+0080-U+00FF is legitimately a byte here and must be decoded. A
        // char above U+00FF can only be real text (a user types "Preis 5€"), so
        // pass it through: masking it to 0xff would turn the Euro into 0xAC and
        // print a quarter sign instead.
        if (code > 0xff) { out += s.charAt(i); continue; }
        if (code < 0x80) { out += s.charAt(i); continue; }
        const cp = parseInt(table.substr((code - 0x80) * 4, 4), 16);
        out += String.fromCodePoint(Number.isNaN(cp) ? REPLACEMENT : cp);
    }
    return out;
}

/** UTF-8 (n=40) over a byte-string, with U+FFFD for malformed sequences. */
function decodeUtf8(s: string): string {
    // Only chars in U+0000-U+00FF are bytes. A char above that is real text
    // the user typed or pasted, so it splits the input: each run of bytes is
    // UTF-8 decoded on its own and the literal chars keep their place.
    // Decoding one run at a time also keeps a byte run that ends mid-sequence
    // from swallowing a real character that followed it.
    const utf8 = new TextDecoder('utf-8');
    let out = '';
    let bytes: number[] = [];
    const flush = () => {
        if (bytes.length === 0) return;
        out += utf8.decode(new Uint8Array(bytes));
        bytes = [];
    };
    for (let i = 0; i < s.length; i++) {
        const code = s.charCodeAt(i);
        if (code > 0xff) { flush(); out += s.charAt(i); }
        else bytes.push(code);
    }
    flush();
    return out;
}

/** One-line description for the viewer settings panel. */
export function describeCodePage(n: number): string {
    const info = CODE_PAGES[n];
    if (!info) return 'Unknown (' + n + ')';
    if (info.resident) return info.label + ' (n=' + n + ') — resident character substitution';
    return info.label + ' (n=' + n + ')';
}
`;

